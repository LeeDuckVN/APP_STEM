function renderSuggestions() {
  const query = searchInput.value.trim().toLowerCase();
  if (query.length < 2) {
    suggestions.hidden = true;
    return;
  }

  const matches = products.filter((product) => productSearchText(product).includes(query)).slice(0, 5);
  suggestions.hidden = matches.length === 0;
  suggestions.innerHTML = matches
    .map((product) => `<button type="button" data-suggestion="${label(product.name)}">${label(product.name)}<br><small>${product.sku}</small></button>`)
    .join("");

  document.querySelectorAll("[data-suggestion]").forEach((button) => {
    button.addEventListener("click", () => {
      searchInput.value = button.dataset.suggestion;
      suggestions.hidden = true;
      renderProducts();
    });
  });
}

function addToCart(productId, qty = 1) {
  const product = products.find((item) => item.id === productId);
  const quantity = Math.max(1, qty);
  const existing = cart.find((item) => item.id === productId);

  if (existing) {
    existing.qty = Math.min(product.inventory, existing.qty + quantity);
  } else {
    cart.push({ id: product.id, qty: Math.min(product.inventory, quantity) });
  }

  saveCart();
  renderCart();
  showToast(t("addedToCart", { qty: quantity, unit: label(product.unit), name: label(product.name) }));
}

function changeCartQty(productId, step) {
  const product = products.find((item) => item.id === productId);
  cart = cart
    .map((item) => (item.id === productId ? { ...item, qty: Math.min(product.inventory, item.qty + step) } : item))
    .filter((item) => item.qty > 0);
  saveCart();
  renderCart();
}

function renderCart() {
  const detailedCart = cart
    .map((item) => ({ ...products.find((product) => product.id === item.id), qty: item.qty }))
    .filter((item) => item.id);
  const itemCount = detailedCart.reduce((sum, item) => sum + item.qty, 0);
  const subtotal = detailedCart.reduce((sum, item) => sum + item.price * item.qty, 0);
  const shipping = subtotal > 0 && subtotal < 500000 ? 30000 : 0;
  const total = subtotal + shipping;

  cartCount.textContent = itemCount;
  cartSubtotal.textContent = formatMoney(subtotal);
  shippingFee.textContent = formatMoney(shipping);
  cartTotal.textContent = formatMoney(total);

  cartItems.innerHTML = detailedCart.length
    ? detailedCart
        .map(
          (item) => `
            <div class="cart-line">
              <div>
                <h3>${label(item.name)}</h3>
                <small>${formatMoney(item.price)} × ${item.qty} ${label(item.unit)}</small>
              </div>
              <div class="cart-line-actions">
                <button type="button" data-cart-step="-1" data-cart-id="${item.id}">−</button>
                <strong>${item.qty}</strong>
                <button type="button" data-cart-step="1" data-cart-id="${item.id}">+</button>
              </div>
            </div>
          `
        )
        .join("")
    : `<p>${t("emptyCart")}</p>`;

  document.querySelectorAll("[data-cart-id]").forEach((button) => {
    button.addEventListener("click", () => changeCartQty(button.dataset.cartId, Number(button.dataset.cartStep)));
  });
}

