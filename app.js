// ===================== Hero Carousel =====================
const carouselTrack = $("#carouselTrack");
const carouselDots = $("#carouselDots");
const carouselPrev = $("#carouselPrev");
const carouselNext = $("#carouselNext");
const carouselEl = $("#heroCarousel");

if (carouselTrack && carouselDots) {
  const slides = Array.from(carouselTrack.querySelectorAll(".carousel-slide"));
  const slideCount = slides.length;
  let currentIndex = 0;
  let autoplayTimer = null;
  let dots = [];
  const AUTOPLAY_INTERVAL = 4500; // 4.5s giữa các ảnh

  function setActiveSlide(next) {
    if (slideCount <= 1 || next === currentIndex || next < 0 || next >= slideCount) return;
    if (slides[currentIndex]) slides[currentIndex].classList.remove("active");
    if (slides[next]) slides[next].classList.add("active");
    dots[currentIndex]?.classList.remove("active");
    dots[next]?.classList.add("active");
    currentIndex = next;
  }

  function nextSlide() {
    if (slideCount > 1) setActiveSlide((currentIndex + 1) % slideCount);
  }

  function prevSlide() {
    if (slideCount > 1) setActiveSlide((currentIndex - 1 + slideCount) % slideCount);
  }

  function restartAutoplay() {
    if (autoplayTimer) clearInterval(autoplayTimer);
    if (slideCount > 1) {
      autoplayTimer = window.setInterval(nextSlide, AUTOPLAY_INTERVAL);
    }
  }

  // Tạo các dot điều hướng
  dots = slides.map((_, i) => {
    const dot = document.createElement("button");
    dot.type = "button";
    dot.className = "carousel-dot";
    if (i === 0) dot.classList.add("active");
    dot.setAttribute("role", "tab");
    dot.setAttribute("aria-label", `Chuyển sang banner ${i + 1}`);
    dot.addEventListener("click", () => {
      setActiveSlide(i);
      restartAutoplay();
    });
    carouselDots.appendChild(dot);
    return dot;
  });

  carouselPrev?.addEventListener("click", () => {
    prevSlide();
    restartAutoplay();
  });
  carouselNext?.addEventListener("click", () => {
    nextSlide();
    restartAutoplay();
  });

  // Xoay vòng tự động
  if (slideCount > 1) {
    restartAutoplay();
  }

  // Pause autoplay khi rê chuột vào carousel
  carouselEl?.addEventListener("mouseenter", () => {
    if (autoplayTimer) clearInterval(autoplayTimer);
  });
  carouselEl?.addEventListener("mouseleave", () => {
    restartAutoplay();
  });

  // Hỗ trợ touch swipe cho mobile
  let touchStartX = 0;
  let touchEndX = 0;

  carouselEl?.addEventListener("touchstart", (e) => {
    touchStartX = e.changedTouches[0].screenX;
  }, { passive: true });

  carouselEl?.addEventListener("touchend", (e) => {
    touchEndX = e.changedTouches[0].screenX;
    const dx = touchEndX - touchStartX;
    if (Math.abs(dx) > 50) {
      if (dx < 0) nextSlide();
      else prevSlide();
      restartAutoplay();
    }
  }, { passive: true });
}

