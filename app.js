/* ===================== Live sync với Admin và các tab khác ===================== */
function reloadStorefrontFromStore() {
  try {
    products = getStoreProducts();
    cart = getStoreCart();
    renderAll();
    renderNewProducts();
    renderCart();
  } catch (e) {
    console.warn("Lỗi khi tải lại dữ liệu từ store:", e);
  }
}

// Lắng nghe sự kiện storage (khi tab khác cập nhật localStorage)
window.addEventListener("storage", (event) => {
  if (!event.key || [STORE_KEYS.products, STORE_KEYS.cart, STORE_KEYS.orders, STORE_KEYS.seeded].includes(event.key)) {
    reloadStorefrontFromStore();
  }
});

// Lắng nghe tín hiệu đồng bộ từ store.js (BroadcastChannel và CustomEvent)
window.addEventListener("store-changed", () => {
  reloadStorefrontFromStore();
});

loadStoreFromMongo().then(reloadStorefrontFromStore).catch(() => {
  console.warn("MongoDB store unavailable; using browser cache.");
});

// Tự động kiểm tra và cập nhật khi người dùng chuyển tab quay lại trang chủ
window.addEventListener("focus", reloadStorefrontFromStore);
document.addEventListener("visibilitychange", () => {
  if (document.visibilityState === "visible") {
    reloadStorefrontFromStore();
  }
});

